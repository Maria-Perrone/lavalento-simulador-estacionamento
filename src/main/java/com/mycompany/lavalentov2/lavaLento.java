    private void btnEntradaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEntradaActionPerformed
        // TODO add your handling code here:
        int selecionado = cbbEntrada.getSelectedIndex(); //SELECIONADO SE REFERE A ESCOLHA DO ENUM.

        LocalTime entrada = null;
        LocalTime saida = null;

        if (selecionado == 0) { // ESTACIONAMENTO
            tipoServicoStr = "Estacionamento";
            entrada = LocalTime.now();
            saida = null;

            //VALIDAÇÃO DE HORARIO.
            //APOS TESTES ADD O "!" PARA QUE A REGRA DE NGC SEJA VALIDA.
            if (entrada.isBefore(HORA_ABERTURA) && (saida.isAfter(HORA_FECHAMENTO))) {
                JOptionPane.showMessageDialog(this, "Estacionamento fechado", "Lava Lento", JOptionPane.WARNING_MESSAGE);
            } else {
                Estacionamento es = new Estacionamento(entrada, saida, txtPlaca.getText(), txtModelo.getText());
                vlServico = 0.0;
            }
        } else if (selecionado == 1) {  //LAVAGEM COMPLETA 
            Estetica est = new Estetica("Completa", txtPlaca.getText(), txtModelo.getText());
            tipoServicoStr = "Lavagem Completa";
            vlServico = est.calcularTotal();
            
        } else if (selecionado == 2) { //LAVAGEM SIMPLES
            Estetica est = new Estetica("Simples", txtPlaca.getText(), txtModelo.getText());
            vlServico = est.calcularTotal();
            tipoServicoStr = "Lavagem Simples";
        }

        String sql = "INSERT INTO registro (placa, modelo, tipo_servico, hora_entrada, hora_saida, valor_total) VALUES (?, ?, ?, ?, ?, ?)";
        // Salvando no Banco de Dados
        try (Connection conn = Conexao.conectar(); PreparedStatement stmt = conn.prepareStatement(sql)) {

            stmt.setString(1, txtPlaca.getText());
            stmt.setString(2, txtModelo.getText());
            stmt.setString(3, tipoServicoStr);
            stmt.setTime(4, entrada != null ? java.sql.Time.valueOf(entrada) : null);
            stmt.setTime(5, saida != null ? java.sql.Time.valueOf(saida) : null);
            stmt.setDouble(6, vlServico);

            stmt.executeUpdate();
            JOptionPane.showMessageDialog(this, "Registro salvo com sucesso!", "Sucesso", JOptionPane.INFORMATION_MESSAGE);
            limparCampos();

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro ao salvar no banco: " + e.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
        }


    }//GEN-LAST:event_btnEntradaActionPerformed

