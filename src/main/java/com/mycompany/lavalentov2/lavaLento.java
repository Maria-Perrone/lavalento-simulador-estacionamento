    private void btnBuscaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscaActionPerformed
        // TODO add your handling code here:
                                             
        String pesquisa = txtBusca.getText().trim();
         
        if (pesquisa.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Digite uma placa para pesquisar!", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }

        LocalTime horaSaida = LocalTime.now(); 
        
        //Atualizar a hora de saída no banco para a placa encontrada
        String updateSql = "UPDATE registro SET hora_saida = ? WHERE placa = ? AND hora_saida IS NULL";

        try (Connection conn = Conexao.conectar(); PreparedStatement updateStmt = conn.prepareStatement(updateSql)) {
            updateStmt.setTime(1, java.sql.Time.valueOf(horaSaida));
            updateStmt.setString(2, pesquisa);
            updateStmt.executeUpdate();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro ao atualizar a saída: " + e.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // 2. SEGUNDO: Busca os dados atualizados para exibir no ticket
        String sql = "SELECT * FROM registro WHERE placa = ? ORDER BY id DESC LIMIT 1"; // Ajuste conforme sua tabela

        try (Connection conn = Conexao.conectar(); PreparedStatement stmt = conn.prepareStatement(sql)) {

            stmt.setString(1, pesquisa);
            ResultSet rs = stmt.executeQuery();
            
            StringBuilder ticket = new StringBuilder();

            if (rs.next()) {
                ticket.append("===============================\n");
                ticket.append("    LAVALENTO COM TALENTO    \n");
                ticket.append("===============================\n");
                ticket.append("Placa: ").append(rs.getString("placa")).append("\n");
                ticket.append("Modelo: ").append(rs.getString("modelo")).append("\n");
                ticket.append("Serviço: ").append(rs.getString("tipo_servico")).append("\n");

                if (rs.getTime("hora_entrada") != null) {
                    ticket.append("Entrada: ").append(rs.getTime("hora_entrada")).append("\n");
                }
                if (rs.getTime("hora_saida") != null) {
                    ticket.append("Saída: ").append(rs.getTime("hora_saida")).append("\n");
                }

                ticket.append("Valor Total: R$ ").append(String.format("%.2f", rs.getDouble("valor_total"))).append("\n");
                ticket.append("===============================\n");

                taTicket.setText(ticket.toString());
            } else {
                taTicket.setText("");
                JOptionPane.showMessageDialog(this, "Nenhum veículo encontrado com esta placa.", "Aviso", JOptionPane.WARNING_MESSAGE);
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro ao buscar no banco: " + e.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
        }
    
    }//GEN-LAST:event_btnBuscaActionPerformed

